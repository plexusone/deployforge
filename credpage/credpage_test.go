package credpage

import (
	"strings"
	"testing"
	"time"

	"github.com/plexusone/systemspec-credential/credspec"

	"github.com/plexusone/deployforge/internal/fleettest"
)

func secret(id string, mutate func(*credspec.Credential)) credspec.Credential {
	parts := strings.Split(id, "/")
	c := credspec.Credential{
		ID: id, Name: parts[len(parts)-1], System: parts[0], Environment: parts[1], Kind: credspec.KindRandomSecret,
		Status: credspec.StatusActive, Owner: "ops", Issuer: credspec.Issuer{Type: credspec.IssuerSelf},
		Generation: credspec.Generation{Method: credspec.MethodRandom, Format: credspec.FormatHex32},
		Stores:     []credspec.Store{{Type: credspec.StoreAWSSSM, Role: credspec.RolePrimary, Account: "hosting", Path: "/example/" + strings.Join(parts[1:], "/")}},
		Rotation:   credspec.Rotation{Policy: credspec.PolicyOnDemand},
		Handling:   credspec.Handling{Generate: credspec.ActorSystem, Distribute: credspec.ActorSystem, Rotate: credspec.ActorHuman},
	}
	if mutate != nil {
		mutate(&c)
	}
	return c
}

func TestRender(t *testing.T) {
	f := fleettest.Fleet()
	reg := credspec.NewRegistry(
		secret("one-cloud/prod/SESSION_KEY", nil),
		secret("one-cloud/prod/API_TOKEN", func(c *credspec.Credential) {
			c.Generation = credspec.Generation{Method: credspec.MethodIssued, Steps: []string{"Create a <token> & copy it."}}
			c.Issuer = credspec.Issuer{Type: "example-issuer", Console: "https://console.example.com"}
			c.Need = credspec.NeedOptional
		}),
		secret("one-cloud/staging/SESSION_KEY", nil),
		secret("other-cloud/prod/SESSION_KEY", nil),
	)
	log := credspec.NewLog()
	at := time.Date(2026, 3, 1, 0, 0, 0, 0, time.UTC)
	if err := log.Append(reg, credspec.Event{Credential: "one-cloud/prod/SESSION_KEY", Type: credspec.EventCreated, At: at, By: "ops"}); err != nil {
		t.Fatal(err)
	}
	page, err := Render(f, "one-cloud", "prod", reg, log, Options{Tool: []string{"deployforge", "credentials"}, Now: func() time.Time { return at }})
	if err != nil {
		t.Fatal(err)
	}
	s := string(page)
	for _, want := range []string{
		"<title>one-cloud prod credentials</title>", "1 of 2 recorded as set up.",
		"generated by credforge (hex32)", `<a href="https://console.example.com">from example-issuer, installed with credforge</a>`,
		"2026-03-01", "not yet", "Create a &lt;token&gt; &amp; copy it.",
		"deployforge credentials setup --system one-cloud --env prod run &lt;step&gt;",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("the page lacks %q", want)
		}
	}
	if strings.Contains(s, "staging/SESSION_KEY") || strings.Contains(s, "other-cloud") || strings.Count(s, "<h1") != 1 {
		t.Error("the page shows another stack's credentials, or two titles")
	}
	if strings.Index(s, "SESSION_KEY") > strings.Index(s, "API_TOKEN") {
		t.Error("an optional credential comes before one needed for launch")
	}
	if _, err := Render(f, "nowhere", "prod", reg, log, Options{}); err == nil {
		t.Error("an unknown app")
	}
}

func TestRenderWithNothingToSetUp(t *testing.T) {
	page, err := Render(fleettest.Fleet(), "one-cloud", "prod", credspec.NewRegistry(), credspec.NewLog(), Options{})
	if err != nil || !strings.Contains(string(page), "Nothing in the registry is left to set up.") {
		t.Errorf("%v\n%s", err, page)
	}
}
