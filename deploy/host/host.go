// Package host renders the script that prepares an app stack's place on its
// host: its Unix user, its directories, its systemd unit, the rotation of its
// log files, and the /etc/hosts lines that keep its calls to its own host
// names on the host. The script is idempotent and does not start the service,
// because a stack has no release to run until its first deploy.
package host

import (
	"bytes"
	"fmt"
	"regexp"
	"strings"
	"text/template"

	"github.com/plexusone/deployforge/deploy/systemd"
	"github.com/plexusone/deployforge/fleet"
)

// unitTerminator ends the here-document that carries the unit file. A unit
// that contained it on a line of its own would end the document early.
const unitTerminator = "DEPLOYFORGE_UNIT_FILE"

// safeName is what a unit and a Unix user may be called. The fleet's own
// validation already guarantees it; the script is shell, so it is checked
// again where it is written.
var safeName = regexp.MustCompile(`^[a-z][a-z0-9-]*[a-z0-9]$`)

var tmpl = template.Must(template.New("host").Parse(`#!/bin/bash
# Generated by ` + "`deployforge host setup {{.App}} {{.Stack}}`" + ` from the fleet document; do not edit by hand.
# Prepares {{.Unit}} on its host: its user, directories and unit. Run as root on
# the host. Idempotent. It does not start the service: there is no release to
# run until the first deploy.
set -eu

unit={{.Unit}}
user={{.User}}
# DEPLOYFORGE_ROOT prefixes the paths this script writes, for testing it in a
# scratch directory. On the host it is empty.
root="${DEPLOYFORGE_ROOT:-}"

id -u "$user" >/dev/null 2>&1 \
  || useradd --system --home-dir "/opt/$unit" --shell /usr/sbin/nologin "$user"

# Releases are root-owned and read-only to the service. Configuration, the
# environment file and key files are root:<user>, 0750, filled by the deploy.
install -d -o root -g root -m 0755 "$root/opt/$unit" "$root/opt/$unit/releases"
install -d -o root -g "$user" -m 0750 "$root/etc/$unit"

tmp="$(mktemp "$root/etc/systemd/system/$unit.service.XXXXXX")"
cat > "$tmp" <<'` + unitTerminator + `'
{{.UnitFile}}` + unitTerminator + `
chmod 0644 "$tmp"
changed=1
if [ -f "$root/etc/systemd/system/$unit.service" ] && cmp -s "$tmp" "$root/etc/systemd/system/$unit.service"; then
  changed=0
fi
mv -f "$tmp" "$root/etc/systemd/system/$unit.service"

{{- if .LogFiles}}
# The app's log files rotate daily by rename, and the app follows the new
# file; a week stays on the host. copytruncate would lose lines.
install -d -o root -g root -m 0755 "$root/etc/logrotate.d"
tmp="$(mktemp "$root/etc/logrotate.d/$unit.XXXXXX")"
cat > "$tmp" <<'` + unitTerminator + `'
{{- range .LogFiles}}
/var/log/{{$.Unit}}/{{.}}{{end}} {
	su {{.User}} {{.User}}
	daily
	rotate 7
	dateext
	missingok
	notifempty
	create 0600 {{.User}} {{.User}}
	compress
	delaycompress
}
` + unitTerminator + `
chmod 0644 "$tmp"
mv -f "$tmp" "$root/etc/logrotate.d/$unit"
{{- end}}

{{range .LoopbackHosts}}
# {{.Host}} resolves to the host itself, so the app's calls to it go to the
# reverse proxy on loopback, never out through a CDN. Added once.
grep -qE '^127\.0\.0\.1[[:space:]]+([^#]*[[:space:]])?{{.Pattern}}([[:space:]]|$)' "$root/etc/hosts" 2>/dev/null \
  || echo "127.0.0.1 {{.Host}}" >> "$root/etc/hosts"
{{end}}
systemctl daemon-reload
systemctl enable "$unit"
if [ "$changed" = 1 ] && systemctl is-active --quiet "$unit"; then
  echo "$unit.service changed while running: restart it to apply (systemctl restart $unit)"
fi
echo "$unit is ready for its first deploy"
`))

type data struct {
	App, Stack, Unit, User string
	UnitFile               string
	LogFiles               []string
	LoopbackHosts          []loopback
}

// loopback is a host name the host resolves to itself.
type loopback struct {
	Host, Pattern string
}

// hostPattern is a host name with nothing a shell or a regular expression
// would read; the fleet's validation already guarantees it.
var hostPattern = regexp.MustCompile(`^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$`)

// loopbackHosts checks each host name the stack resolves to itself.
func loopbackHosts(hosts []string) ([]loopback, error) {
	var out []loopback
	for _, h := range hosts {
		if !hostPattern.MatchString(h) {
			return nil, fmt.Errorf("host: %q is not a safe host name", h)
		}
		out = append(out, loopback{Host: h, Pattern: strings.ReplaceAll(h, ".", `\.`)})
	}
	return out, nil
}

// logFile is a plain file name, safe in the logrotate configuration; the
// fleet's validation already guarantees it.
var logFile = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]*$`)

// Render writes the host-setup script for one stack of one app.
func Render(f *fleet.Fleet, app, stack string) ([]byte, error) {
	unitFile, err := systemd.Render(f, app, stack)
	if err != nil {
		return nil, err
	}
	a, st, err := f.Stack(app, stack)
	if err != nil {
		return nil, fmt.Errorf("host: %w", err)
	}
	loop, err := loopbackHosts(st.LoopbackHosts)
	if err != nil {
		return nil, err
	}
	for _, l := range a.LogFiles {
		if !logFile.MatchString(l) {
			return nil, fmt.Errorf("host: log file %q is not a plain file name", l)
		}
	}
	unit, user := f.Unit(a, stack), f.UnixUser(a, stack)
	if !safeName.MatchString(unit) || !safeName.MatchString(user) {
		return nil, fmt.Errorf("host: %q or %q is not a safe name", unit, user)
	}
	for _, line := range bytes.Split(unitFile, []byte("\n")) {
		if string(line) == unitTerminator {
			return nil, fmt.Errorf("host: the unit contains a line that would end its here-document")
		}
	}
	if len(unitFile) == 0 || unitFile[len(unitFile)-1] != '\n' {
		unitFile = append(unitFile, '\n')
	}
	var b bytes.Buffer
	d := data{App: app, Stack: stack, Unit: unit, User: user, UnitFile: string(unitFile), LogFiles: a.LogFiles, LoopbackHosts: loop}
	if err := tmpl.Execute(&b, d); err != nil {
		return nil, fmt.Errorf("host: %w", err)
	}
	return b.Bytes(), nil
}
